using System.Text;
using System.Text.RegularExpressions;

using Generellem.Llm.AzureOpenAI;
using Generellem.Rag;

using OpenAI.Chat;

namespace Generellem.Llm.Local;

/// <summary>
/// Offline LLM that returns extractive answers from retrieved context (no external API).
/// </summary>
public partial class LocalLlmService : ILlm
{
    public Task<TResponse> PromptAsync<TResponse>(IChatRequest request, CancellationToken cancellationToken)
        where TResponse : IChatResponse
    {
        if (request is not AzureOpenAIChatRequest chatRequest)
            throw new ArgumentException($"LocalLlmService expects {nameof(AzureOpenAIChatRequest)}.", nameof(request));

        ArgumentNullException.ThrowIfNull(chatRequest.Messages);

        string systemText = string.Empty;
        string userText = string.Empty;

        foreach (ChatMessage message in chatRequest.Messages)
        {
            string content = AzureOpenAIChatRequest.GetRequestContent(message);
            switch (message)
            {
                case SystemChatMessage:
                    systemText = content;
                    break;
                case UserChatMessage:
                    userText = content;
                    break;
            }
        }

        string responseText = IsIntentSummarization(systemText)
            ? ExtractUserQuery(systemText) ?? userText
            : BuildExtractiveAnswer(systemText, userText);

        IChatResponse response = new AzureOpenAIChatResponse(responseText);
        return Task.FromResult((TResponse)response);
    }

    static bool IsIntentSummarization(string systemText) =>
        systemText.Contains("Chat History:", StringComparison.OrdinalIgnoreCase) ||
        systemText.Contains("User's query:", StringComparison.OrdinalIgnoreCase) ||
        systemText.Contains("infer the user's real intent", StringComparison.OrdinalIgnoreCase);

    static string? ExtractUserQuery(string systemText)
    {
        Match match = UserQueryRegex().Match(systemText);
        return match.Success ? match.Groups[1].Value.Trim() : null;
    }

    static string BuildExtractiveAnswer(string systemText, string userText)
    {
        string context = ExtractContext(systemText);

        if (string.IsNullOrWhiteSpace(context))
        {
            return
                "[Local demo profile — not production AI]\n\n" +
                "No retrieved context was available. Ingest documents first, or try a different question.";
        }

        string[] paragraphs = context
            .Split(["\n\n", "\r\n\r\n"], StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);

        List<string> selected = SelectRelevantParagraphs(paragraphs, userText);

        StringBuilder sb = new();
        sb.AppendLine("[Local demo profile — not production AI]");
        sb.AppendLine();
        sb.AppendLine("Based on the retrieved documentation:");
        sb.AppendLine();

        foreach (string paragraph in selected)
        {
            string trimmed = paragraph.Trim();
            if (trimmed.Length > 600)
                trimmed = trimmed[..600].TrimEnd() + "…";
            sb.AppendLine(trimmed);
            sb.AppendLine();
        }

        sb.Append("This answer is extractive (not generated by a cloud LLM). ");
        sb.Append("Use --profile Ollama or --profile Azure for model-generated answers.");

        return sb.ToString().TrimEnd();
    }

    static string ExtractContext(string systemText)
    {
        int delimited = systemText.IndexOf(UntrustedContext.Start, StringComparison.Ordinal);
        if (delimited >= 0)
        {
            int contentStart = delimited + UntrustedContext.Start.Length;
            int contentEnd = systemText.IndexOf(UntrustedContext.End, contentStart, StringComparison.Ordinal);
            if (contentEnd < 0)
                return systemText[contentStart..].Trim();

            return systemText[contentStart..contentEnd].Trim();
        }

        int contextMarker = systemText.IndexOf("Context:", StringComparison.OrdinalIgnoreCase);
        if (contextMarker < 0)
            return string.Empty;

        string after = systemText[(contextMarker + "Context:".Length)..];
        Match fenced = FencedCodeRegex().Match(after);
        if (fenced.Success)
            return fenced.Groups[1].Value.Trim();

        return after.Trim().Trim('`').Trim();
    }

    static List<string> SelectRelevantParagraphs(string[] paragraphs, string userText)
    {
        if (paragraphs.Length == 0)
            return [];

        HashSet<string> queryTokens = Tokenize(userText);
        if (queryTokens.Count == 0)
            return paragraphs.Take(2).ToList();

        return paragraphs
            .Select(p => (Paragraph: p, Score: ScoreOverlap(p, queryTokens)))
            .OrderByDescending(x => x.Score)
            .ThenByDescending(x => x.Paragraph.Length)
            .Take(3)
            .Where(x => x.Score > 0 || paragraphs.Length <= 3)
            .Select(x => x.Paragraph)
            .DefaultIfEmpty(paragraphs[0])
            .ToList();
    }

    static int ScoreOverlap(string paragraph, HashSet<string> queryTokens)
    {
        HashSet<string> tokens = Tokenize(paragraph);
        int score = 0;
        foreach (string token in queryTokens)
        {
            if (tokens.Contains(token))
                score++;
        }
        return score;
    }

    static HashSet<string> Tokenize(string text)
    {
        string[] parts = text.ToLowerInvariant()
            .Split([' ', '\t', '\r', '\n', '.', ',', ';', ':', '!', '?', '(', ')', '"', '\''],
                StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);

        HashSet<string> tokens = new(StringComparer.Ordinal);
        foreach (string part in parts)
        {
            if (part.Length < 3)
                continue;
            tokens.Add(part);
        }
        return tokens;
    }

    [GeneratedRegex(@"User's query:\s*(.+)$", RegexOptions.IgnoreCase | RegexOptions.Singleline)]
    private static partial Regex UserQueryRegex();

    [GeneratedRegex(@"```\s*(.*?)\s*```", RegexOptions.Singleline)]
    private static partial Regex FencedCodeRegex();
}
